/// The language of a file by its name in lower case, its name first, then its longest extension known.
pub(super) fn language_of(name: &str) -> Option<&'static str> {
    if let Some((language, _, _)) = LANGUAGES.iter().find(|(_, _, names)| names.contains(&name)) {
        return Some(language);
    }
    super::extensions(name).find_map(|extension| {
        LANGUAGES
            .iter()
            .find(|(_, extensions, _)| extensions.contains(&extension))
            .map(|(language, _, _)| *language)
    })
}
