//! The words of the buttons of the title bar the window draws itself (`window.caption-buttons`).

/// **Minimize**, as the screen reader and its tooltip say it.
pub const MINIMIZE: &str = "Minimize";
/// **Maximize**, while the window is not maximized.
pub const MAXIMIZE: &str = "Maximize";
/// **Restore**, in place of **Maximize** while the window is maximized.
pub const RESTORE: &str = "Restore";
/// **Close**.
pub const CLOSE: &str = "Close";
