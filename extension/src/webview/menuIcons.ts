/** The codicon of the icon of an operation in a menu, by the card of the operation; none for those no icon says. */
export function operationIcon(feature: string): string | undefined {
  const meaning = OPERATION_ICONS[feature];
  return meaning && MEANING_ICONS[meaning];
}

/**
 * The codicon an item of a menu draws at the left of its words: the check while an item that switches or chooses is
 * on, and nothing else for such an item; else the icon of its operation, or of its meaning; none for an item no icon says.
 */
export function itemIcon(item: Pick<MenuItem, 'checked' | 'feature' | 'icon'>): string | undefined {
  if (item.checked !== undefined) return item.checked ? MEANING_ICONS.CHOSEN : undefined;
  if (item.icon) return MEANING_ICONS[item.icon];
  return item.feature ? operationIcon(item.feature) : undefined;
}
